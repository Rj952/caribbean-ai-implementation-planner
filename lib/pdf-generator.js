// Browser-side .pdf generation using jsPDF.
// Caribbean palette and clean editorial layout.

import { jsPDF } from 'jspdf';
import autoTable from 'jspdf-autotable';
import { PRINCIPLES, GDP_SECTORS, COMMITMENTS } from './data';

// Caribbean palette (RGB)
// Jamaica-primary palette for PDF export.
// Black anchors headings, green is the section accent, gold is emphasis.
const SEA = [11, 11, 11];      // Jamaica black
const TEAL = [0, 122, 45];     // Jamaica green-deep (AA on white)
const SUN = [201, 161, 0];     // Jamaica gold-deep (AA on white)
const INK = [26, 26, 26];
const MUTE = [92, 104, 115];
const SAND = [242, 238, 223];

const PAGE_W = 210; // A4 mm
const PAGE_H = 297;
const MARGIN = 18;
const CONTENT_W = PAGE_W - MARGIN * 2;

class PdfWriter {
  constructor(title) {
    this.doc = new jsPDF({ unit: 'mm', format: 'a4' });
    this.doc.setProperties({
      title,
      creator: 'Caribbean AI Implementation Planner',
      author: 'Generated by Caribbean AI Implementation Planner'
    });
    this.y = MARGIN;
    this.pageNum = 1;
    this.title = title;
    this.drawHeader();
    this.drawFooter();
  }

  drawHeader() {
    const d = this.doc;
    d.setFillColor(...SEA);
    d.rect(0, 0, PAGE_W, 6, 'F');
    d.setFillColor(...SUN);
    d.rect(0, 6, PAGE_W, 1, 'F');
  }

  drawFooter() {
    const d = this.doc;
    d.setFontSize(8);
    d.setTextColor(...MUTE);
    d.text('Caribbean AI Implementation Planner · Based on Jowallah (2026)', MARGIN, PAGE_H - 8);
    d.text(`Page ${this.pageNum}`, PAGE_W - MARGIN, PAGE_H - 8, { align: 'right' });
  }

  newPage() {
    this.doc.addPage();
    this.pageNum += 1;
    this.y = MARGIN + 4;
    this.drawHeader();
    this.drawFooter();
  }

  ensureSpace(needed) {
    if (this.y + needed > PAGE_H - MARGIN) {
      this.newPage();
    }
  }

  spacer(mm = 4) {
    this.y += mm;
  }

  h1(text) {
    this.ensureSpace(18);
    this.spacer(6);
    const d = this.doc;
    d.setFont('helvetica', 'bold');
    d.setFontSize(18);
    d.setTextColor(...SEA);
    const lines = d.splitTextToSize(text, CONTENT_W);
    d.text(lines, MARGIN, this.y + 6);
    this.y += 6 + lines.length * 7;
    // gold underline
    d.setDrawColor(...SUN);
    d.setLineWidth(0.6);
    d.line(MARGIN, this.y - 1, MARGIN + 30, this.y - 1);
    this.y += 4;
  }

  h2(text) {
    this.ensureSpace(12);
    this.spacer(3);
    const d = this.doc;
    d.setFont('helvetica', 'bold');
    d.setFontSize(13);
    d.setTextColor(...SEA);
    const lines = d.splitTextToSize(text, CONTENT_W);
    d.text(lines, MARGIN, this.y + 5);
    this.y += 5 + lines.length * 5.5;
    this.spacer(2);
  }

  h3(text) {
    this.ensureSpace(10);
    const d = this.doc;
    d.setFont('helvetica', 'bold');
    d.setFontSize(11);
    d.setTextColor(...TEAL);
    const lines = d.splitTextToSize(text, CONTENT_W);
    d.text(lines, MARGIN, this.y + 5);
    this.y += 5 + lines.length * 5;
    this.spacer(1);
  }

  p(text, opts = {}) {
    if (!text) text = '—';
    const d = this.doc;
    d.setFont(opts.bold ? 'helvetica' : 'helvetica', opts.bold ? 'bold' : opts.italic ? 'italic' : 'normal');
    d.setFontSize(opts.size || 10);
    d.setTextColor(...(opts.color || INK));
    const lines = d.splitTextToSize(String(text), CONTENT_W - (opts.indent || 0));
    for (const line of lines) {
      this.ensureSpace(6);
      d.text(line, MARGIN + (opts.indent || 0), this.y + 4);
      this.y += 5;
    }
    this.spacer(1);
  }

  bullet(text) {
    const d = this.doc;
    d.setFont('helvetica', 'normal');
    d.setFontSize(10);
    d.setTextColor(...INK);
    const lines = d.splitTextToSize(text, CONTENT_W - 6);
    this.ensureSpace(6);
    d.setTextColor(...SUN);
    d.text('•', MARGIN, this.y + 4);
    d.setTextColor(...INK);
    for (let i = 0; i < lines.length; i++) {
      this.ensureSpace(6);
      d.text(lines[i], MARGIN + 5, this.y + 4);
      this.y += 5;
    }
    this.spacer(1);
  }

  callout(text, color = SAND) {
    const d = this.doc;
    d.setFont('helvetica', 'italic');
    d.setFontSize(9);
    d.setTextColor(...MUTE);
    const lines = d.splitTextToSize(text, CONTENT_W - 8);
    const blockH = lines.length * 4.5 + 5;
    this.ensureSpace(blockH);
    d.setFillColor(...color);
    d.rect(MARGIN, this.y, CONTENT_W, blockH, 'F');
    d.setDrawColor(...SUN);
    d.setLineWidth(0.6);
    d.line(MARGIN, this.y, MARGIN, this.y + blockH);
    let cursor = this.y + 4;
    for (const line of lines) {
      d.text(line, MARGIN + 4, cursor);
      cursor += 4.5;
    }
    this.y += blockH + 3;
  }

  rule() {
    this.ensureSpace(6);
    const d = this.doc;
    d.setDrawColor(...SUN);
    d.setLineWidth(0.4);
    d.line(MARGIN, this.y + 2, PAGE_W - MARGIN, this.y + 2);
    this.y += 6;
  }

  multiline(text) {
    if (!text) {
      this.p('[To be drafted]', { italic: true, color: MUTE });
      return;
    }
    text.split(/\r?\n/).forEach(line => {
      if (line.trim()) this.p(line);
      else this.spacer(2);
    });
  }

  metaTable(rows) {
    autoTable(this.doc, {
      startY: this.y,
      margin: { left: MARGIN, right: MARGIN },
      head: [],
      body: rows,
      theme: 'plain',
      styles: {
        fontSize: 10,
        cellPadding: { top: 3, right: 4, bottom: 3, left: 4 },
        lineColor: [216, 210, 189],
        lineWidth: 0.2
      },
      columnStyles: {
        0: {
          fillColor: SAND,
          textColor: SEA,
          fontStyle: 'bold',
          cellWidth: 50
        },
        1: { textColor: INK }
      }
    });
    this.y = this.doc.lastAutoTable.finalY + 6;
  }

  save(filename) {
    this.doc.save(filename);
  }
}

export function exportPdf(data, filename = 'national-ai-implementation-plan.pdf') {
  const c = data.country || '[Country Name]';
  const today = data.date || new Date().toISOString().slice(0, 10);
  const w = new PdfWriter(`${c} — National AI Implementation Plan`);

  // Title block
  w.doc.setFont('helvetica', 'bold');
  w.doc.setFontSize(9);
  w.doc.setTextColor(...SUN);
  w.doc.text('CARIBBEAN AI IMPLEMENTATION PLAN', MARGIN, w.y + 8);
  w.y += 10;

  w.doc.setFont('helvetica', 'bold');
  w.doc.setFontSize(24);
  w.doc.setTextColor(...SEA);
  const titleLines = w.doc.splitTextToSize('National AI Implementation Plan', CONTENT_W);
  w.doc.text(titleLines, MARGIN, w.y + 9);
  w.y += titleLines.length * 9 + 2;

  w.doc.setFont('helvetica', 'italic');
  w.doc.setFontSize(16);
  w.doc.setTextColor(...TEAL);
  w.doc.text(c, MARGIN, w.y + 7);
  w.y += 12;

  w.p(`Working Document — Version ${data.version || '1.0'}`, { italic: true, color: MUTE });
  w.rule();

  w.metaTable([
    ['Country', c],
    ['Population', data.population || '—'],
    ['Lead Agency', data.leadAgency || '—'],
    ['Prepared By', data.preparedBy || '—'],
    ['Date', today],
    ['Status', 'Working Draft']
  ]);

  // 1. Executive Summary
  w.h1('1. Executive Summary');
  w.p(
    `This implementation plan operationalises the Caribbean AI Deployment Blueprint (Jowallah, 2026) for the specific institutional, constitutional, and economic conditions of ${c}. It is structured around the seven guiding principles drawn from the Jowallah Governance Wheel and the three-sector pathway (public, private, and GDP-critical industries), with education positioned as the strategic anchor.`
  );
  w.p(
    'The plan is a working document. It is intended to be reviewed by the National AI Council, contextualised through public consultation, and revised through scheduled iteration cycles. It is not a finished policy. It is the substrate from which a finished policy can be built.'
  );

  // 2. Vision
  w.h1('2. National AI Vision');
  w.h2('2.1 Vision Statement');
  w.multiline(data.vision);
  w.h2('2.2 Strategic Priorities');
  const priors = data.priorities.filter(Boolean);
  if (priors.length) priors.forEach((pr, i) => w.p(`${i + 1}. ${pr}`));
  else w.p('[Priorities to be drafted — typically 3–5 high-level commitments.]', { italic: true, color: MUTE });
  w.h2('2.3 Constitutional and Cultural Anchors');
  w.multiline(data.constitutional);
  if (data.anchors) {
    w.p('Additional Anchors:', { bold: true });
    w.multiline(data.anchors);
  }
  w.h2('2.4 Linguistic Context');
  w.multiline(data.languages);
  w.h2('2.5 Existing AI Initiatives');
  w.multiline(data.existing);
  w.h2('2.6 Higher Education Landscape');
  w.multiline(data.institutions);

  // 3. Seven Principles
  w.h1('3. The Seven Principles — Implementation Plan');
  w.p('The seven guiding principles are drawn from the Jowallah Governance Wheel (Jowallah, 2026, forthcoming). They are operational, not ornamental. None of them works alone.', { italic: true, color: MUTE });
  PRINCIPLES.forEach((pr, i) => {
    const pd = data.principles[pr.id] || {};
    const gap = (pd.target || 0) - (pd.current || 0);
    w.h2(`Principle ${i + 1} — ${pr.name}`);
    w.p(`Current: ${pd.current ?? '—'}/5    Target: ${pd.target ?? '—'}/5    Gap: ${gap >= 0 ? '+' + gap : gap}`, { bold: true, color: TEAL });
    w.p(`Lead Agency: ${pd.lead || '[To be assigned]'}`, { bold: true });
    w.p(pr.desc, { italic: true, color: MUTE });
    w.p('Implementation Actions:', { bold: true });
    w.multiline(pd.actions);
    w.callout(`Suggested from the Blueprint: ${pr.suggest}`);
  });

  // 4. Three Sectors
  w.h1('4. The Three-Sector Pathway');
  w.h2('4.1 Public Sector');
  w.p(`Lead Coordinating Body: ${data.publicSector.lead || '[To be assigned]'}`, { bold: true });
  w.p('Implementation Priorities:', { bold: true });
  w.multiline(data.publicSector.priorities);
  w.h2('4.2 Private Sector');
  w.p(`Lead Coordinating Body: ${data.privateSector.lead || '[To be assigned]'}`, { bold: true });
  w.p('Implementation Priorities:', { bold: true });
  w.multiline(data.privateSector.priorities);
  w.h2('4.3 GDP-Critical Production Sectors');
  w.p('Sectors Selected for Priority Deployment:', { bold: true });
  if (data.gdpSelected.length) {
    data.gdpSelected.forEach(id => {
      const s = GDP_SECTORS.find(x => x.id === id);
      w.bullet(s ? s.label : id);
    });
  } else w.p('[No sectors selected]', { italic: true, color: MUTE });
  w.p('Cross-Sectoral Priorities:', { bold: true });
  w.multiline(data.gdpPriorities);

  // 5. Compact
  w.h1('5. The University Compact');
  w.h2('5.1 Lead University');
  w.p(data.compact.leadUni || '[Lead university to be designated as the national node of the Caribbean University AI Compact.]');
  w.h2('5.2 Additional Signatories');
  w.multiline(data.compact.signatories);
  w.h2('5.3 Six Commitments');
  COMMITMENTS.forEach(co => {
    w.p(`${data.compact.selected[co.id] ? '☑' : '☐'}  ${co.label} — ${co.desc}`);
  });

  // 6. Roadmap
  w.h1('6. Implementation Roadmap');
  w.h2('6.1 Phase 1 — Foundation (2026–2027)');
  w.multiline(data.phase1);
  w.h2('6.2 Phase 2 — Expansion (2028–2029)');
  w.multiline(data.phase2);
  w.h2('6.3 Phase 3 — Consolidation (2030–2031)');
  w.multiline(data.phase3);

  // 7. Risks
  w.h1('7. Risk Register');
  const risks = data.risks.filter(r => r.risk || r.mitigation);
  if (risks.length) {
    risks.forEach((r, i) => {
      w.p(`Risk ${i + 1}: ${r.risk || '[Risk]'}`, { bold: true });
      w.p(`Mitigation: ${r.mitigation || '[Mitigation]'}`);
      w.spacer(2);
    });
  } else {
    w.p('[Top risks and mitigations to be specified.]', { italic: true, color: MUTE });
  }

  // 8. Accountability
  w.h1('8. Accountability and Reporting');
  w.p('This plan adopts the accountability commitments of the Caribbean AI Deployment Blueprint:');
  ['Annual State of AI in the Nation report, tabled in Parliament, accessible in plain language.',
   'Public register of government AI deployments, updated quarterly.',
   'Independent academic evaluation funded as a line item, not a discretionary grant.',
   'Civil society audit rights, including for unions, consumer organisations, and disability advocacy bodies.',
   'Twenty-four-month policy review cycle.'].forEach(t => w.bullet(t));

  // 9. References
  w.h1('9. References');
  [
    'Jowallah, R. (2026). Caribbean AI Deployment Blueprint. Working paper.',
    'Jowallah, R. (Ed.). (forthcoming). Sovereign Intelligence: A Caribbean Framework for AI Leadership in Education and Policy. IGI Global.',
    'Simmons, E., Ramsewak, D., Kissoon, P., & Bissessar, C. (2024). Caribbean Artificial Intelligence Policy Roadmap. Caribbean Telecommunications Union.',
    'UNESCO. (2021). Recommendation on the Ethics of Artificial Intelligence.',
    'OECD. (2024). OECD Principles on Artificial Intelligence (revised).',
    'NIST. (2023). AI Risk Management Framework (AI RMF 1.0).',
    'Carroll, S. R. et al. (2020). The CARE Principles for Indigenous Data Governance. Data Science Journal, 19(1), 43.',
    'Heeks, R. (2022). Digital inequality beyond the digital divide. Information Technology for Development, 28(4), 688–704.',
    'Mohamed, S., Png, M.-T., & Isaac, W. (2020). Decolonial AI. Philosophy & Technology, 33(4), 659–684.'
  ].forEach(t => w.bullet(t));

  w.rule();
  w.p('Working document prepared using the Caribbean AI Implementation Planner.', { italic: true, color: MUTE, size: 9 });
  w.p('Based on the Caribbean AI Deployment Blueprint by Dr. Rohan Jowallah (2026).', { italic: true, color: MUTE, size: 9 });

  w.save(filename);
}

/**
 * Export an evaluation report as a styled PDF.
 */
export function exportEvaluationPdf(report, filename = 'plan-evaluation-report.pdf') {
  const w = new PdfWriter('Plan Evaluation Report');

  w.doc.setFont('helvetica', 'bold');
  w.doc.setFontSize(9);
  w.doc.setTextColor(...SUN);
  w.doc.text('PLAN EVALUATION REPORT', MARGIN, w.y + 8);
  w.y += 10;

  w.doc.setFont('helvetica', 'bold');
  w.doc.setFontSize(22);
  w.doc.setTextColor(...SEA);
  const t = w.doc.splitTextToSize('Evaluation Against the Caribbean AI Deployment Blueprint', CONTENT_W);
  w.doc.text(t, MARGIN, w.y + 9);
  w.y += t.length * 8 + 4;

  w.p(`Source file: ${report.sourceName || '—'}`, { color: MUTE });
  w.p(`Word count: ${report.wordCount?.toLocaleString() || '—'}`, { color: MUTE });
  w.p(`Evaluation date: ${new Date().toISOString().slice(0, 10)}`, { color: MUTE });
  w.rule();

  w.h1('Overall Score');
  w.p(`Coverage: ${report.overall.score}% — ${report.overall.band}`, { bold: true, color: TEAL, size: 12 });
  w.p(report.overall.summary);

  w.h1('Strengths');
  if (report.strengths.length) report.strengths.forEach(s => w.bullet(s));
  else w.p('— No clear strengths identified above the threshold.', { italic: true, color: MUTE });

  w.h1('Critical Gaps');
  if (report.gaps.length) report.gaps.forEach(g => w.bullet(g));
  else w.p('— No critical gaps identified.', { italic: true, color: MUTE });

  w.h1('Section-by-Section Findings');
  report.sections.forEach(s => {
    w.h2(s.name);
    w.p(`Status: ${s.status} (${s.score}%)`, { bold: true, color: TEAL });
    w.p(s.notes);
    if (s.missing && s.missing.length) {
      w.p('Concepts not detected in the uploaded plan:', { bold: true });
      s.missing.forEach(m => w.bullet(m));
    }
  });

  w.h1('Recommended Action Plan');
  w.p('These actions are prioritised by the size of the gap between what your uploaded plan addresses and what the Blueprint specifies. Treat them as amendment hooks for the next revision cycle.', { italic: true, color: MUTE });
  report.actions.forEach((a, i) => {
    w.h3(`Action ${i + 1} — ${a.title}`);
    if (a.principle) {
      w.p(`${a.principle}  ·  ${a.score ?? 0}% coverage`, { italic: true, color: MUTE });
    }
    const priorityColor =
      a.priority === 'Critical' ? [11, 11, 11]    :
      a.priority === 'High'     ? [200, 16, 46]   :
      a.priority === 'Medium'   ? [201, 161, 0]   : [0, 155, 58];
    w.p(`Priority: ${a.priority}`, { bold: true, color: priorityColor });
    w.p(`Rationale: ${a.rationale}`);
    w.p('Recommended steps:', { bold: true });
    a.steps.forEach(st => w.bullet(st));
  });

  w.rule();
  w.p('Evaluation generated by the Caribbean AI Implementation Planner.', { italic: true, color: MUTE, size: 9 });
  w.p('Heuristic indicators are derived from the Caribbean AI Deployment Blueprint (Jowallah, 2026).', { italic: true, color: MUTE, size: 9 });

  w.save(filename);
}
